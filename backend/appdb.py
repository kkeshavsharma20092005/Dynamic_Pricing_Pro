# PostgreSQL types: REAL there is 4-byte and would round timestamps to minutes.
PG_SCHEMA = (SCHEMA
             .replace("id INTEGER PRIMARY KEY", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
             .replace(" REAL", " DOUBLE PRECISION")
             .replace("INTEGER", "BIGINT"))


class _PgCursor:
    def __init__(self, cursor, inserted_id=None):
        self._cursor, self.lastrowid = cursor, inserted_id

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()


class _PgConnection:
    """Just enough of sqlite3.Connection for this app's queries."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql, params=()):
        sql = sql.replace("?", "%s")
        returning = sql.lstrip().upper().startswith("INSERT INTO") and "ON CONFLICT" not in sql.upper()
        cursor = self._conn.execute(sql + (" RETURNING id" if returning else ""), params)
        return _PgCursor(cursor, cursor.fetchone()["id"] if returning else None)


_pool = None


def _pg_pool():
    # One small pool per process. Opening a TLS connection per query to a hosted database
    # would add a round trip to every request.
    global _pool
    if _pool is None:
        _pool = ConnectionPool(DATABASE_URL, min_size=1, max_size=5, open=True,
                               # No server-side prepared statements: hosted poolers in
                               # transaction mode (Neon, Supabase) hand each transaction to
                               # a different server connection, where they do not exist.
                               kwargs={"row_factory": dict_row, "autocommit": False,
                                       "prepare_threshold": None},
                               check=ConnectionPool.check_connection)
        atexit.register(close)
    return _pool


def close():
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


@contextmanager
def connect():
    if USE_POSTGRES:
        # Commits when the block succeeds, rolls back if it raises.
        with _pg_pool().connection() as conn:
            yield _PgConnection(conn)
        return
    conn = sqlite3.connect(DB_PATH, timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        with conn:
            yield conn
    finally:
        conn.close()


def migrate_users_to_per_role_accounts():
    """Older databases allowed one account per number across all roles."""
    conn = sqlite3.connect(DB_PATH, timeout=10)
    try:
        row = conn.execute("SELECT sql FROM sqlite_master WHERE name = 'users'").fetchone()
        if row and "UNIQUE (phone, role)" not in row[0]:
            conn.executescript("""
                PRAGMA foreign_keys = OFF;
                BEGIN;
                CREATE TABLE users_new (
                    id INTEGER PRIMARY KEY, phone TEXT NOT NULL, name TEXT NOT NULL,
                    role TEXT NOT NULL CHECK (role IN ('rider', 'driver', 'admin')),
                    vehicle TEXT, password_hash TEXT NOT NULL, salt TEXT NOT NULL,
                    created_at REAL NOT NULL, UNIQUE (phone, role));
                INSERT INTO users_new SELECT id, phone, name, role, vehicle, password_hash, salt, created_at FROM users;
                DROP TABLE users;
                ALTER TABLE users_new RENAME TO users;
                COMMIT;
            """)
    finally:
        conn.close()


# Columns added after the first release. Older databases get them on start.
ADDED_COLUMNS = [
    ("users", "email", "TEXT"),
    ("users", "gender", "TEXT"),
    ("users", "kyc", "TEXT"),
    ("users", "kyc_note", "TEXT"),
    ("users", "plate", "TEXT"),
    ("verifications", "rc_image", "TEXT"),
    ("rides", "women_only", "INTEGER NOT NULL DEFAULT 0"),
    ("rides", "pay_token", "TEXT"),
    ("rides", "paid_at", "REAL"),
    ("rides", "payment_method", "TEXT"),
]


def init_db():
    if USE_POSTGRES:
        with _pg_pool().connection() as conn:
            for statement in PG_SCHEMA.split(";"):
                if statement.strip():
                    conn.execute(statement)
            for table, column, kind in ADDED_COLUMNS:
                # Same types as PG_SCHEMA: a 4-byte REAL would round timestamps to minutes.
                kind = kind.replace("INTEGER", "BIGINT").replace("REAL", "DOUBLE PRECISION")
                conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {kind}")
            # paid_at was first added as REAL; widen it where that already happened.
            conn.execute("ALTER TABLE rides ALTER COLUMN paid_at TYPE DOUBLE PRECISION")
        return
    migrate_users_to_per_role_accounts()
    with connect() as conn:
        conn.executescript(SCHEMA)
        for table, column, kind in ADDED_COLUMNS:
            existing = {row["name"] for row in conn.execute(f"PRAGMA table_info({table})").fetchall()}
            if column not in existing:
                conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {kind}")


def backend_name() -> str:
    return "postgres" if USE_POSTGRES else "sqlite"


def hash_password(password: str, salt: str) -> str:
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), PBKDF2_ROUNDS).hex()


def create_user(phone, name, role, password, vehicle=None, email=None) -> int:
    salt = secrets.token_hex(16)
    with connect() as conn:
        cursor = conn.execute(
            "INSERT INTO users (phone, name, role, vehicle, email, password_hash, salt, created_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            (phone, name, role, vehicle, email, hash_password(password, salt), salt, time.time()))
        return cursor.lastrowid


def set_gender_once(user_id, gender) -> bool:
    """Record an account's gender. False if it was already set: it cannot be changed here."""
    with connect() as conn:
        return conn.execute("UPDATE users SET gender = ? WHERE id = ? AND gender IS NULL",
                            (gender, user_id)).rowcount == 1


# ID checks. The document images are kept only until an admin has reviewed them.
def save_verification(user_id, kind, document, id_image, selfie, licence_image, plate=None, rc_image=None):
    with connect() as conn:
        conn.execute(
            "INSERT INTO verifications (user_id, kind, document, id_image, selfie, licence_image, rc_image, "
            "status, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, 'pending', ?)",
            (user_id, kind, document, id_image, selfie, licence_image, rc_image, time.time()))
        conn.execute("UPDATE users SET kyc = 'pending', kyc_note = NULL, plate = COALESCE(?, plate) WHERE id = ?",
                     (plate, user_id))


def plate_in_use(plate, user_id) -> bool:
    """Another driver, approved or waiting, already has this number plate."""
    with connect() as conn:
        row = conn.execute("SELECT 1 FROM users WHERE plate = ? AND id != ? AND role = 'driver' "
                           "AND kyc IN ('pending', 'approved')", (plate, user_id)).fetchone()
    return row is not None


def list_verifications(status, limit=50):
    with connect() as conn:
        rows = conn.execute(
            "SELECT v.*, u.name, u.phone, u.role, u.vehicle, u.gender, u.plate FROM verifications v "
            "JOIN users u ON u.id = v.user_id WHERE v.status = ? ORDER BY v.created_at "
            + ("ASC" if status == "pending" else "DESC") + " LIMIT ?", (status, limit)).fetchall()
    return [dict(r) for r in rows]


def get_verification(verification_id):
    with connect() as conn:
        row = conn.execute("SELECT * FROM verifications WHERE id = ?", (verification_id,)).fetchone()
    return dict(row) if row else None


def review_verification(verification_id, approved, gender, note) -> int | None:
    """Record the decision and delete the images. The user's id, or None if already reviewed."""
    status = "approved" if approved else "rejected"
    with connect() as conn:
        row = conn.execute("SELECT user_id FROM verifications WHERE id = ? AND status = 'pending'",
                           (verification_id,)).fetchone()
        if row is None:
            return None
        changed = conn.execute(
            "UPDATE verifications SET status = ?, note = ?, reviewed_at = ?, id_image = '', selfie = '', "
            "licence_image = NULL, rc_image = NULL WHERE id = ? AND status = 'pending'",
            (status, note, time.time(), verification_id)).rowcount
        if not changed:
            return None
        if approved:
            conn.execute("UPDATE users SET kyc = 'approved', kyc_note = NULL, gender = ? WHERE id = ?",
                         (gender, row["user_id"]))
        else:
            conn.execute("UPDATE users SET kyc = 'rejected', kyc_note = ? WHERE id = ?", (note, row["user_id"]))
        return row["user_id"]


def find_user(phone, role):
    with connect() as conn:
        row = conn.execute("SELECT * FROM users WHERE phone = ? AND role = ?", (phone, role)).fetchone()
    return dict(row) if row else None


def set_password(user_id, password):
    salt = secrets.token_hex(16)
    with connect() as conn:
        conn.execute("UPDATE users SET password_hash = ?, salt = ? WHERE id = ?",
                     (hash_password(password, salt), salt, user_id))


# Password reset codes. Only a salted hash of the code is stored, never the code itself.
def save_reset_code(user_id, code, expires_at):
    salt = secrets.token_hex(16)
    with connect() as conn:
        conn.execute(
            "INSERT INTO password_resets (user_id, code_hash, salt, expires_at, attempts, sent_at) "
            "VALUES (?, ?, ?, ?, 0, ?) ON CONFLICT(user_id) DO UPDATE SET code_hash = excluded.code_hash, "
            "salt = excluded.salt, expires_at = excluded.expires_at, attempts = 0, sent_at = excluded.sent_at",
            (user_id, hash_password(code, salt), salt, expires_at, time.time()))


def get_reset(user_id):
    with connect() as conn:
        row = conn.execute("SELECT * FROM password_resets WHERE user_id = ?", (user_id,)).fetchone()
    return dict(row) if row else None


def reset_code_matches(reset: dict, code: str) -> bool:
    return hmac.compare_digest(reset["code_hash"], hash_password(code, reset["salt"]))


def count_reset_attempt(user_id):
    with connect() as conn:
        conn.execute("UPDATE password_resets SET attempts = attempts + 1 WHERE user_id = ?", (user_id,))


def delete_reset(user_id):
    with connect() as conn:
        conn.execute("DELETE FROM password_resets WHERE user_id = ?", (user_id,))


def verify_user(phone, password, role):
    with connect() as conn:
        row = conn.execute("SELECT * FROM users WHERE phone = ? AND role = ?", (phone, role)).fetchone()
    if row is None:
        return None
    if not hmac.compare_digest(row["password_hash"], hash_password(password, row["salt"])):
        return None
    return dict(row)


def get_user(user_id):
    with connect() as conn:
        row = conn.execute("SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()
    return dict(row) if row else None


def get_setting(key, default=None):
    with connect() as conn:
        row = conn.execute("SELECT value FROM settings WHERE key = ?", (key,)).fetchone()
    return json.loads(row["value"]) if row else default


def set_setting(key, value):
    with connect() as conn:
        conn.execute(
            "INSERT INTO settings (key, value) VALUES (?, ?) "
            "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
            (key, json.dumps(value)))


DEFAULT_ADMIN_PHONE = "6006083467"


def ensure_admin() -> str | None:
    """
    Make the admin account match ADMIN_PHONE and ADMIN_PASSWORD on every start, so changing
    either setting changes the login. There is no password in the code: without
    ADMIN_PASSWORD a new admin gets a generated one, returned for one-time display.
    """
    phone = os.environ.get("ADMIN_PHONE", DEFAULT_ADMIN_PHONE)
    wanted = os.environ.get("ADMIN_PASSWORD")
    with connect() as conn:
        admin = conn.execute("SELECT * FROM users WHERE phone = ? AND role = 'admin'", (phone,)).fetchone()
        if admin is None:
            # A new ADMIN_PHONE moves the existing admin account to it instead of adding a second admin.
            admin = conn.execute("SELECT * FROM users WHERE role = 'admin' ORDER BY id LIMIT 1").fetchone()
            if admin is not None:
                conn.execute("UPDATE users SET phone = ? WHERE id = ?", (phone, admin["id"]))
    if admin is None:
        password = wanted or secrets.token_urlsafe(9)
        create_user(phone, "Admin", "admin", password)
        return None if wanted else f"{phone} / {password}"
    if wanted and not hmac.compare_digest(admin["password_hash"], hash_password(wanted, admin["salt"])):
        set_password(admin["id"], wanted)
    return None
